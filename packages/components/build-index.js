/**
 * Writes the package-root barrel, src/index.js and src/index.d.ts, from the
 * components in src/.
 *
 * Why this exists: hand-maintained barrels made every component pull request
 * conflict on the same lines. Each `src/<name>.js` other than `index.js` is one
 * component. Its exports come from `src/<name>.js`, and its tag names come from
 * the `HTMLElementTagNameMap` entries in `src/<name>.d.ts`. Both outputs are
 * git-ignored and rebuilt by `pnpm build`.
 */

import { readdir, readFile, writeFile } from "node:fs/promises";

const SRC = "src";

const names = (await readdir(SRC))
  .filter((file) => file.endsWith(".js") && file !== "index.js")
  .map((file) => file.slice(0, -".js".length))
  .sort();

const components = [];
for (const name of names) {
  const js = await readFile(`${SRC}/${name}.js`, "utf8");
  const dts = await readFile(`${SRC}/${name}.d.ts`, "utf8");

  const exports = [...js.matchAll(/^export (?:class|const|function) (\w+)/gm)]
    .map((match) => match[1])
    .sort();
  const defines = exports.filter((exported) => /^define[A-Z]/.test(exported));
  if (defines.length !== 1) {
    throw new Error(`src/${name}.js must export one define* function, found ${defines.length}.`);
  }

  const tagMap = dts.match(/interface HTMLElementTagNameMap \{([^}]*)\}/)?.[1] ?? "";
  const tags = [...tagMap.matchAll(/"([a-z][\w-]*)": (\w+);/g)].map(([, tagName, className]) => ({
    tagName,
    attributes: `${className}Attributes`,
  }));
  if (tags.length === 0) {
    throw new Error(`src/${name}.d.ts declares no HTMLElementTagNameMap entry.`);
  }
  for (const { attributes } of tags) {
    if (!new RegExp(`export interface ${attributes}\\b`).test(dts)) {
      throw new Error(`src/${name}.d.ts must export interface ${attributes}.`);
    }
  }

  components.push({ name, exports, define: defines[0], tags });
}

const header = "// Generated by build-index.js from the components in src/. Do not edit.\n";

await writeFile(
  `${SRC}/index.js`,
  `${header}
/**
 * @taproot-ds/web-components
 *
 * Importing this module registers every element with its default tag name.
 * Import from a subpath (e.g. "…/button") to register selectively, or use the
 * exported \`define*\` helpers to register under a custom tag name.
 */

${components.map(({ name, define }) => `import { ${define} } from "./${name}.js";\n`).join("")}
${components.map(({ name, exports }) => `export { ${exports.join(", ")} } from "./${name}.js";\n`).join("")}
${components.map(({ define }) => `${define}();\n`).join("")}`,
  "utf8",
);

await writeFile(
  `${SRC}/index.d.ts`,
  `${header}
${components
  .map(
    ({ name, tags }) =>
      `import type { ${tags
        .map((tag) => tag.attributes)
        .sort()
        .join(", ")} } from "./${name}.js";\n`,
  )
  .join("")}
${components.map(({ name }) => `export * from "./${name}.js";\n`).join("")}
/**
 * The attributes each element accepts, keyed by default tag name. Map it onto a
 * framework's intrinsic elements to type templates, such as JSX.
 */
export interface ElementAttributes {
${components
  .flatMap(({ tags }) => tags)
  .map(({ tagName, attributes }) => `  "${tagName}": ${attributes};\n`)
  .join("")}}
`,
  "utf8",
);

console.log(`${SRC}/index.js and ${SRC}/index.d.ts ← ${components.length} components`);
