/**
 * Writes the source files that follow from the knowledge records, so adding a
 * component edits none of them:
 *
 * - `src/<name>.d.ts` for each component, from its binding and contract.
 * - `src/index.js` and `src/index.d.ts`, the package-root barrel.
 *
 * Each web-component binding for this package names its module (the component
 * slug), class (`host.export`), registration function
 * (`host.registration.export`), and tag. Property and attribute types come from
 * the contract's parameter kinds and enum values, mapped through the binding.
 * The files are committed; CI fails when a build changes, adds, or removes one. Generated
 * files that no component owns any more are deleted.
 */

import { access, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { openCatalog } from "@stevegreco/design-system-knowledge/retrieve";

const SRC = new URL("./src/", import.meta.url);
const HEADER = "// Generated by build-sources.js from the knowledge records. Do not edit.\n";
/** Longest line oxfmt leaves on one line. */
const PRINT_WIDTH = 100;
/** Files this run writes; any other generated file in `src/` is stale. */
const written = new Set();

const { name: packageName } = JSON.parse(
  await readFile(new URL("./package.json", import.meta.url), "utf8"),
);

const catalog = await openCatalog();
const elements = catalog
  .list({ type: "binding" })
  .map((summary) => catalog.get(summary.id))
  .filter((binding) => binding.host.platform === "web-component")
  .filter((binding) => binding.host.package === packageName)
  .map((binding) => {
    const component = catalog.get(binding.relations.implements[0]);
    const slug = component.id.slice("component.".length);
    return {
      slug,
      component,
      host: binding.host,
      tagName: binding.host.defaultTagName,
      className: binding.host.export,
      defineName: binding.host.registration.export,
      typePrefix: pascalCase(slug),
    };
  })
  .sort((left, right) => (left.slug < right.slug ? -1 : left.slug > right.slug ? 1 : 0));

for (const { slug } of elements) {
  try {
    await access(new URL(`${slug}.js`, SRC));
  } catch {
    throw new Error(`A binding names component ${slug}, but src/${slug}.js does not exist.`);
  }
}

for (const element of elements) {
  await write(`${element.slug}.d.ts`, [HEADER, ...elementTypes(element)]);
}

await write("index.js", [
  HEADER,
  "/**",
  " * @stevegreco/design-system-components",
  " *",
  " * Importing this module registers every element with its default tag name.",
  ' * Import from a subpath (e.g. "…/button") to register selectively, or use the',
  " * exported `define*` helpers to register under a custom tag name.",
  " */",
  "",
  ...elements.map(({ slug, defineName }) => `import { ${defineName} } from "./${slug}.js";`),
  "",
  ...elements.map(
    ({ slug, className, defineName }) =>
      `export { ${className}, ${defineName} } from "./${slug}.js";`,
  ),
  "",
  ...elements.map(({ defineName }) => `${defineName}();`),
]);

await write("index.d.ts", [
  HEADER,
  ...elements.map(
    ({ slug, className }) => `import type { ${className}Attributes } from "./${slug}.js";`,
  ),
  "",
  ...elements.map(({ slug }) => `export * from "./${slug}.js";`),
  "",
  "/**",
  " * The attributes each element accepts, keyed by default tag name. Map it onto a",
  " * framework's intrinsic elements to type templates, such as JSX.",
  " */",
  "export interface ElementAttributes {",
  ...elements.map(
    ({ tagName, className }) => `  ${JSON.stringify(tagName)}: ${className}Attributes;`,
  ),
  "}",
]);

await removeStale();

/** The `.d.ts` lines for one element. */
function elementTypes({ component, host, tagName, className, defineName, typePrefix }) {
  const aliases = [];
  const attributes = [];
  const properties = [];

  for (const [name, parameter] of Object.entries(component.contract.parameters ?? {})) {
    const mapped = host.parameters[name];
    let type = parameter.kind === "boolean" ? "boolean" : "string";
    let defaultNote;
    if (parameter.kind === "enum") {
      type = `${typePrefix}${pascalCase(mapped.property ?? name)}`;
      const hostValue = (value) => mapped.values?.[value] ?? value;
      aliases.push(...unionAlias(type, Object.keys(parameter.values).map(hostValue)));
      if (parameter.default !== undefined) {
        defaultNote = `Defaults to \`${JSON.stringify(hostValue(parameter.default))}\`.`;
      }
    }
    const comment = docComment([parameter.description, defaultNote], "  ");
    // Every framework already types the global ARIA attributes.
    if (mapped.attribute && !mapped.attribute.startsWith("aria-")) {
      attributes.push(...comment, `  ${memberKey(mapped.attribute)}?: ${type};`);
    }
    if (mapped.property) {
      properties.push(...comment, `  ${memberKey(mapped.property)}: ${type};`);
    }
  }

  for (const [name, property] of Object.entries(host.properties ?? {})) {
    properties.push(
      ...docComment([property.description], "  "),
      `  ${property.readonly ? "readonly " : ""}${memberKey(name)}: ${property.type};`,
    );
  }

  const statics = host.formAssociation ? ["  static readonly formAssociated: true;"] : [];
  const methods = [];
  if (host.formAssociation?.fieldsetDisables) {
    methods.push("  formDisabledCallback(disabled: boolean): void;");
  }
  if (host.formAssociation?.submitsValue) {
    methods.push(
      "  formResetCallback(): void;",
      "  formStateRestoreCallback(state: string | null, mode: string): void;",
    );
  }
  if (host.focus) {
    const inner = host.anatomy[host.focus.forwardsTo]?.element ?? host.focus.forwardsTo;
    methods.push(
      `  /** Focuses the inner \`<${inner}>\`. */`,
      "  focus(options?: FocusOptions): void;",
      `  /** Blurs the inner \`<${inner}>\`. */`,
      "  blur(): void;",
    );
  }

  const tag = `\`<${tagName}>\``;
  const define = host.registration.supportsAliases
    ? [
        `/** Registers ${tag}, or an alias when given a tag name. Safe to call more than once. */`,
        `export declare function ${defineName}(tagName?: string): void;`,
      ]
    : [
        `/** Registers ${tag}. Safe to call more than once. */`,
        `export declare function ${defineName}(): void;`,
      ];

  return [
    ...(aliases.length > 0 ? [...aliases, ""] : []),
    `/** The attributes ${tag} accepts, for typing framework templates. */`,
    `export interface ${className}Attributes {`,
    ...attributes,
    "}",
    "",
    ...docComment([`${tag}: ${component.summary}`]),
    `export declare class ${className} extends HTMLElement {`,
    ...joinGroups([statics, properties, methods]),
    "}",
    "",
    ...define,
    "",
    "declare global {",
    "  interface HTMLElementTagNameMap {",
    `    ${JSON.stringify(tagName)}: ${className};`,
    "  }",
    "}",
  ];
}

/** `export type Name = "a" | "b";`, broken one value per line when it is too long. */
function unionAlias(name, values) {
  const members = values.map((value) => JSON.stringify(value));
  const line = `export type ${name} = ${members.join(" | ")};`;
  if (line.length <= PRINT_WIDTH) return [line];
  return [
    `export type ${name} =`,
    ...members.map((member, index) => `  | ${member}${index === members.length - 1 ? ";" : ""}`),
  ];
}

function docComment(sentences, indent = "") {
  const text = sentences.filter(Boolean).join(" ").replaceAll("*/", "*\\/");
  return text ? [`${indent}/** ${text} */`] : [];
}

function joinGroups(groups) {
  return groups
    .filter((group) => group.length > 0)
    .flatMap((group, index) => (index === 0 ? group : ["", ...group]));
}

function memberKey(name) {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
}

function pascalCase(name) {
  return name.replace(/(?:^|[-_])([a-z])/g, (_match, letter) => letter.toUpperCase());
}

async function write(file, lines) {
  await writeFile(new URL(file, SRC), `${lines.join("\n")}\n`, "utf8");
  written.add(file);
  console.log(`src/${file}`);
}

/** Delete generated files that no component owns any more, such as a removed binding's types. */
async function removeStale() {
  for (const file of await readdir(SRC)) {
    if (written.has(file) || !/\.(?:d\.ts|js)$/.test(file)) continue;
    const text = await readFile(new URL(file, SRC), "utf8");
    if (!text.startsWith(HEADER)) continue;
    await rm(new URL(file, SRC));
    console.log(`src/${file} (removed)`);
  }
}
