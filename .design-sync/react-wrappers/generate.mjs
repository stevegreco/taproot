// Generates thin React wrappers for @taproot-ds/web-components from the package's
// own custom-elements.json, so Claude Design (which renders React) can build
// with the real <ds-*> elements. Run from the repo root:
//   node .design-sync/react-wrappers/generate.mjs
// Output: .design-sync/react-wrappers/dist/{index.js,index.d.ts} (gitignored).
//
// Each wrapper renders its element and nothing else. Attributes are always
// rendered; a provided prop is also assigned to the element's property after
// render, because form controls stop following their attributes once a person
// has interacted with them. Events are attached with addEventListener.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "../..");
const manifest = JSON.parse(
  readFileSync(join(repo, "packages/components/dist/custom-elements.json"), "utf8"),
);
const pkg = JSON.parse(readFileSync(join(repo, "packages/components/package.json"), "utf8"));

const pascal = (s) => s.replace(/(^|-)([a-z])/g, (_, __, c) => c.toUpperCase());
const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const eventProp = (name) => "on" + pascal(name);
const doc = (text, indent = "  ") =>
  text
    ? `${indent}/**\n${text
        .trim()
        .split("\n")
        .map((l) => `${indent} * ${l}`.trimEnd())
        .join("\n")}\n${indent} */\n`
    : "";
const key = (name) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name));

const elements = [];
for (const mod of manifest.modules) {
  for (const d of mod.declarations ?? []) {
    if (!d.customElement || !d.tagName) continue;
    const writable = new Set(
      (d.members ?? [])
        .filter((m) => m.kind === "field" && !m.readonly && !m.static && !m.privacy)
        .map((m) => m.name),
    );
    const attrs = (d.attributes ?? []).map((a) => {
      const prop = a.fieldName ?? (a.name.startsWith("aria-") ? a.name : camel(a.name));
      return {
        attr: a.name,
        prop,
        type: a.type?.text ?? "string",
        description: a.description,
        default: a.default,
        // Assign the property too when the element has a writable one.
        live: Boolean(a.fieldName && writable.has(a.fieldName)),
      };
    });
    const events = (d.events ?? []).map((e) => ({
      name: e.name,
      prop: eventProp(e.name),
      description: e.description,
    }));
    elements.push({
      name: d.name.replace(/^Ds/, ""),
      tag: d.tagName,
      summary: d.summary,
      description: d.description,
      attrs,
      events,
      slots: (d.slots ?? []).filter((s) => s.name),
      defaultSlot: (d.slots ?? []).some((s) => !s.name),
    });
  }
}
elements.sort((a, b) => a.name.localeCompare(b.name));

// -- index.js -----------------------------------------------------------------
const js = `// Generated by .design-sync/react-wrappers/generate.mjs. Do not edit.
import "../../../packages/components/src/index.js";
import { createElement, forwardRef, useCallback, useLayoutEffect, useRef } from "react";

function wrap(tag, displayName, attrs, events) {
  const Component = forwardRef(function (props, forwardedRef) {
    const node = useRef(null);
    const rest = {};
    const out = {};
    const live = [];
    const handlers = {};
    const byProp = new Map(attrs.map((a) => [a[1], a]));
    for (const [k, v] of Object.entries(props)) {
      const a = byProp.get(k);
      if (a) {
        const [attr, prop, isLive] = a;
        if (v === undefined || v === null || v === false) continue;
        out[attr] = v === true ? "" : String(v);
        if (isLive) live.push([prop, v]);
      } else if (k in events) handlers[events[k]] = v;
      else if (k === "className") rest.class = v;
      else rest[k] = v;
    }
    // Live props: unset booleans are false, so a controlled checkbox can uncheck.
    for (const [attr, prop, isLive, isBool] of attrs)
      if (isLive && isBool && props[prop] === false) live.push([prop, false]);

    useLayoutEffect(() => {
      const el = node.current;
      if (!el) return;
      for (const [prop, v] of live) if (el[prop] !== v) el[prop] = v;
    });
    const latest = useRef(handlers);
    latest.current = handlers;
    const names = Object.keys(handlers).sort().join(",");
    useLayoutEffect(() => {
      const el = node.current;
      if (!el || !names) return;
      const offs = names.split(",").map((type) => {
        const fn = (event) => latest.current[type]?.(event);
        el.addEventListener(type, fn);
        return () => el.removeEventListener(type, fn);
      });
      return () => offs.forEach((off) => off());
    }, [names]);
    const ref = useCallback((el) => {
      node.current = el;
      if (typeof forwardedRef === "function") forwardedRef(el);
      else if (forwardedRef) forwardedRef.current = el;
    }, [forwardedRef]);
    return createElement(tag, { ...rest, ...out, ref, suppressHydrationWarning: true });
  });
  Component.displayName = displayName;
  return Component;
}

${elements
  .map(
    (e) =>
      `export const ${e.name} = wrap(${JSON.stringify(e.tag)}, ${JSON.stringify(e.name)}, ${JSON.stringify(
        e.attrs.map((a) => [a.attr, a.prop, a.live, a.type === "boolean"]),
      )}, ${JSON.stringify(Object.fromEntries(e.events.map((ev) => [ev.prop, ev.name])))});`,
  )
  .join("\n")}
`;

// -- index.d.ts -----------------------------------------------------------------
const dts = `// Generated by .design-sync/react-wrappers/generate.mjs. Do not edit.
import type * as React from "react";

/** Props every wrapper passes through to its element. */
interface HostProps {
  /** Children land in the element's default slot, or in a named slot with \`slot\`. */
  children?: React.ReactNode;
  /** Places this component in a named slot of its parent (for example "actions"). */
  slot?: string;
  id?: string;
  className?: string;
  style?: React.CSSProperties;
  [attribute: \`aria-\${string}\`]: string | undefined;
  [attribute: \`data-\${string}\`]: string | undefined;
}

${elements
  .map((e) => {
    const props = e.attrs
      .map((a) => {
        const lines = [a.description, a.default ? `@default ${a.default}` : ""]
          .filter(Boolean)
          .join("\n");
        return `${doc(lines)}  ${key(a.prop)}?: ${a.type};`;
      })
      .concat(
        e.events.map(
          (ev) =>
            `${doc(`${ev.description ?? ""}\nListens for the element's \`${ev.name}\` event; read state from \`event.currentTarget\`.`)}  ${ev.prop}?: (event: Event & { currentTarget: ${e.name}Element }) => void;`,
        ),
      )
      .join("\n");
    const element = e.attrs
      .filter((a) => a.live)
      .map((a) => `${key(a.prop)}: ${a.type};`)
      .join(" ");
    const slots = e.slots.length
      ? `\n\nSlots: ${e.slots.map((s) => `\`${s.name}\`${s.description ? ` (${s.description.replace(/\.$/, "")})` : ""}`).join("; ")}. Put a child in one with \`slot="<name>"\`.`
      : "";
    const head = `${e.summary ?? ""}\n\n${e.description ?? ""}\n\nRenders the \`<${e.tag}>\` web component from @taproot-ds/web-components.${slots}`;
    return `/** The \`<${e.tag}>\` element, as event handlers and refs receive it. */
export type ${e.name}Element = HTMLElement & { ${element} };

export interface ${e.name}Props extends HostProps {
${props}
}

${doc(head, "")}export declare const ${e.name}: React.ForwardRefExoticComponent<${e.name}Props & React.RefAttributes<${e.name}Element>>;
`;
  })
  .join("\n")}`;

// -- taproot.css: fonts, tokens, page base -----------------------------------------
// The packages do not ship font files; the web setup loads them from Google Fonts
// (packages/components/implementation/README.md). Same URL here.
const fonts =
  "https://fonts.googleapis.com/css2?family=Lora:ital,wght@0,400..700;1,400..700&family=Source+Sans+3:wght@300..900&family=JetBrains+Mono:wght@400;500;600&display=swap";
const css = [
  `/* Generated by .design-sync/react-wrappers/generate.mjs. Do not edit. */`,
  `@import url("${fonts}");`,
  readFileSync(join(repo, "packages/tokens/dist/css/tokens.css"), "utf8"),
  readFileSync(join(repo, "packages/tokens/dist/css/base.css"), "utf8"),
].join("\n");

mkdirSync(join(here, "dist"), { recursive: true });
writeFileSync(join(here, "dist/taproot.css"), css);
writeFileSync(join(here, "dist/index.js"), js);
writeFileSync(join(here, "dist/index.d.ts"), dts);
writeFileSync(
  join(here, "package.json"),
  JSON.stringify(
    {
      name: "@taproot-ds/react-wrappers",
      version: pkg.version,
      private: true,
      description:
        "Generated React wrappers for @taproot-ds/web-components, for the Claude Design sync only.",
      type: "module",
      main: "./dist/index.js",
      module: "./dist/index.js",
      types: "./dist/index.d.ts",
    },
    null,
    2,
  ) + "\n",
);
console.log(
  `react-wrappers: ${elements.length} wrappers (${elements.map((e) => e.name).join(", ")})`,
);
